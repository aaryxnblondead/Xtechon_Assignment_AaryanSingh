async function seedFlights() {
  try {
    const mongoUri = process.env.MONGODB_URI || 'mongodb://localhost:27017/flight-booking';
    await mongoose.connect(mongoUri);
    logger.info('✅ Connected to MongoDB');

    await Flight.deleteMany({});
    logger.info('🗑️  Cleared existing flights');

    const result = await Flight.insertMany(flights);
    logger.info(`✅ Successfully seeded ${result.length} flights`);

    await mongoose.disconnect();
  } catch (error) {
    logger.error('❌ Seeding failed:', error);
    process.exit(1);
  }
}

seedFlights();
